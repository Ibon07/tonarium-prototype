import test from 'node:test';
import assert from 'node:assert/strict';
import { advanceFantasyWorld, applyFantasyAction, newFantasyProfile, startFantasyActivity } from './fantasy-engine.ts';
import { FANTASY_JOBS, FANTASY_QUESTS } from './fantasy-data.ts';
import { FANTASY_RELICS } from './fantasy-relic-catalog.ts';
import { fantasyOccultAction, fantasyOccultActionError, fantasyOccultActionValid, fantasyOccultDungeonClaim, fantasyOccultKnowledge, validFantasyOccult } from './fantasy-occult.ts';
import { fantasyJobPathDiscovered } from './fantasy-job-discovery.ts';
import { FANTASY_PRIEST_BRANCHES, applyFantasyPriestAction, fantasyPriestActionError, fantasyPriestGrowthStatus, fantasyPriestServiceQuest, syncFantasyPriestGrowth, validFantasyPriestGrowth, fantasyPriestCombatSkill } from './fantasy-priest-growth.ts';

const profile = () => applyFantasyAction(newFantasyProfile(), { type: 'create', source: 'human', gender: 'female', name: '星を探す人' }, () => .99).profile;
test('star discovery requires completed night observation on the star island with actual mage practice', () => {
  const p = profile(), c = p.character!; c.job = 'mage'; c.jobXp.mage = 100; c.location = 'starfall-isle'; c.hour = 20;
  c.readBooks = ['mirrorwake-voyage', 'mana-primer']; c.skillXp = { [FANTASY_JOBS.find(job => job.id === 'mage')!.skills[0].id]: 20 }; c.practice = { explore: 10 };
  assert.equal(fantasyJobPathDiscovered(c, 'mage-star'), false);
  assert.ok(fantasyOccultActionError({ ...p, character: { ...c, hour: 12 } }, { type: 'occultObserve' }));
  assert.ok(fantasyOccultActionError({ ...p, character: { ...c, location: 'starspire' } }, { type: 'occultObserve' }));
  assert.ok(fantasyOccultActionError({ ...p, character: { ...c, job: 'priest' } }, { type: 'occultObserve' }));
  const done = fantasyOccultAction(p, { type: 'occultObserve' }, () => .99)!;
  assert.equal(done.error, undefined); assert.equal(done.profile.character!.hour, 22);
  assert.equal(fantasyJobPathDiscovered(done.profile.character!, 'mage-star'), true);
  assert.equal(validFantasyOccult(done.profile.character!), true);
});
test('every assigned profession has a ruin relic and genuine claim receipts cannot be replayed', () => {
  for (const job of FANTASY_JOBS.filter(job => job.id !== 'unassigned')) assert.ok(FANTASY_RELICS.some(relic => relic.job === job.id), job.id);
  const p = profile(), c = p.character!; c.job = 'warrior'; c.location = 'oldwatch';
  assert.deepEqual(fantasyOccultDungeonClaim(c, 'oldwatch', 'watchcrypt'), []);
  c.dungeon = { sites: { oldwatch: { revealed: ['watchcrypt'], inspected: [], findings: [], detected: [], disarmed: [], sprung: [], cleared: ['watchcrypt'], claimed: ['watchcrypt'], inspectionDays: {} } } };
  const found = fantasyOccultDungeonClaim(c, 'oldwatch', 'watchcrypt'); assert.ok(found.length);
  assert.deepEqual(fantasyOccultDungeonClaim(c, 'oldwatch', 'watchcrypt'), []);
  const relic = FANTASY_RELICS.find(relic => relic.id === found[0])!;
  assert.equal(fantasyJobPathDiscovered(c, relic.path), false);
  const used = fantasyOccultAction(p, { type: 'occultRelic', relic: relic.id }, () => .99)!;
  assert.equal(used.error, undefined); assert.equal(fantasyJobPathDiscovered(used.profile.character!, relic.path), true);
  assert.ok(fantasyOccultAction(used.profile, { type: 'occultRelic', relic: relic.id }, () => .99)!.error);
  assert.equal(validFantasyOccult(used.profile.character!), true);
  assert.deepEqual(fantasyOccultKnowledge({ ...used.profile.character!, job: 'warrior' }), { cores: [], runes: [] });
});
