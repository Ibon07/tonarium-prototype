test('new priest paths stay hidden without relics and saint recognition needs deeper actual service and practice', () => {
  assert.deepEqual(FANTASY_PRIEST_BRANCHES.map(branch => branch.id), ['care', 'ward', 'oath', 'pilgrim', 'inquisitor', 'paladin', 'saint']);
  const c = profile().character!; c.job = 'priest'; c.jobXp.priest = 100; c.readBooks = ['remedies-and-rites', 'traveler-guide', 'words-and-promises']; c.visited = ['hearth', 'suncourt'];
  syncFantasyPriestGrowth(c);
  c.occult = { version: 1, starObservations: [], relicClaims: [], relics: ['relic-priest-saint'], usedRelics: ['relic-priest-saint'] };
  assert.equal(fantasyJobPathDiscovered(c, 'priest-saint'), true);
  assert.ok(fantasyPriestActionError(c, { type: 'priestBranch', branch: 'saint' }));
  assert.equal(fantasyPriestGrowthStatus(c).saintEligible, false);
  c.priestGrowth!.branch = 'paladin';
  assert.deepEqual(fantasyOccultKnowledge(c).cores, ['blessing']);
  c.priestGrowth!.branch = 'saint'; assert.deepEqual(fantasyOccultKnowledge(c).cores, ['blessing', 'miracle']);
  c.job = 'warrior'; assert.deepEqual(fantasyOccultKnowledge(c).cores, []);
});
test('saint path is attainable through a real ruin testament, deep service and earned proficiency', () => {
  let p = profile(); const c = p.character!; c.job = 'priest'; c.jobXp.priest = 300; c.hour = 1000; c.gold = 1000;
  c.location = 'eclipsevault'; c.visited = ['hearth', 'suncourt', 'mooncity', 'eclipsevault'];
  c.completed = FANTASY_QUESTS.filter(quest => fantasyPriestServiceQuest(quest.id)).slice(0, 20).map(quest => quest.id);
  c.readBooks = ['traveler-guide', 'remedies-and-rites', 'words-and-promises']; c.lastPrayerDay = 9;
  c.skillXp = { [FANTASY_JOBS.find(job => job.id === 'priest')!.skills[0].id]: 100 };
  syncFantasyPriestGrowth(c);
  c.priestGrowth!.prayerDays = Array.from({ length: 10 }, (_, day) => day);
  c.priestGrowth!.prayerTemples = Object.fromEntries(c.priestGrowth!.prayerDays.map(day => [String(day), 'hearth']));
  c.priestGrowth!.vows = c.completed.slice(0, 6).map((quest, index) => ({ quest, acceptedAt: 10 + index, hour: 20 + index, location: 'hearth', outcome: 'fulfilled' }));
  c.dungeon = { sites: { eclipsevault: { revealed: ['eclipsethrone'], inspected: [], findings: [], detected: [], disarmed: [], sprung: [], cleared: ['eclipsethrone'], claimed: ['eclipsethrone'], inspectionDays: {} } } };
  assert.deepEqual(fantasyOccultDungeonClaim(c, 'eclipsevault', 'eclipsethrone'), ['relic-priest-saint']);
  p = fantasyOccultAction(p, { type: 'occultRelic', relic: 'relic-priest-saint' })!.profile;
  p.character!.location = 'hearth';
  assert.equal(fantasyPriestGrowthStatus(p.character!).saintEligible, true);
  assert.equal(applyFantasyPriestAction(p.character!, { type: 'priestBranch', branch: 'saint' }).error, undefined);
  assert.equal(validFantasyPriestGrowth(p.character!), true);
  assert.equal(validFantasyOccult(p.character!), true);
  assert.deepEqual(fantasyOccultKnowledge(p.character!).cores, ['blessing', 'miracle']);
  assert.equal(fantasyPriestCombatSkill('priest-inquisitor-brand')!.selfOnly, true);
  assert.equal(fantasyPriestCombatSkill('priest-paladin-vigil')!.selfOnly, true);
  const forged = structuredClone(p.character!); forged.occult!.relics.push('relic-priest-paladin');
  assert.equal(validFantasyOccult(forged), false);
});
test('scheduled stargazing learns nothing until the shared two-hour vigil has completed', () => {
  const p = profile(), c = p.character!; c.job = 'mage'; c.jobXp.mage = 100; c.location = 'starfall-isle'; c.hour = 20;
  c.skillXp = { [FANTASY_JOBS.find(job => job.id === 'mage')!.skills[0].id]: 12 }; c.practice = { explore: 5 };
  const original = structuredClone(p);
  const bad = fantasyOccultAction(p, { type: 'occultObserve' }, () => .9, { advanceTime: false, startedAt: 10 })!;
  assert.ok(bad.error); assert.deepEqual(p, original);
  const started = startFantasyActivity(p, { type: 'occultObserve' }, 20, () => .99);
  assert.equal(started.error, undefined); assert.equal(started.profile.activity!.endsAt, 22);
  assert.equal(fantasyJobPathDiscovered(started.profile.character!, 'mage-star'), false);
  assert.equal(fantasyJobPathDiscovered(advanceFantasyWorld(started.profile, 21.99).profile.character!, 'mage-star'), false);
  const done = advanceFantasyWorld(started.profile, 22).profile;
  assert.equal(fantasyJobPathDiscovered(done.character!, 'mage-star'), true);
  assert.equal(validFantasyOccult(done.character!), true);
});
