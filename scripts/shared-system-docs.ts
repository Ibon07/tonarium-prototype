function fieldTable(fields: Record<string, ValueSchema>) {
  return Object.keys(fields).length ? rows(['이름', '자료형', '기본값', '최솟값', '최댓값'], Object.entries(fields).sort(([a], [b]) => order(a, b)).map(([name, field]) => [code(name), code(field.type), code(JSON.stringify(field.default)), field.min === undefined ? '제한 없음' : code(String(field.min)), field.max === undefined ? '제한 없음' : code(String(field.max))])) : '등록된 필드가 없습니다.';
}

function portTable(ports: Record<string, SystemPort>) {
  return Object.keys(ports).length ? rows(['이벤트 ID', '전달 데이터'], Object.entries(ports).sort(([a], [b]) => order(a, b)).map(([name, port]) => [code(name), Object.entries(port.payload).sort(([a], [b]) => order(a, b)).map(([key, type]) => code(`${key}: ${type}`)).join(', ') || '없음'])) : '등록된 이벤트가 없습니다.';
}

