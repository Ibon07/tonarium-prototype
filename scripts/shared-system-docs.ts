export const GENERATED_SHARED_SYSTEM_DOCS = '<!-- Generated by scripts/shared-system-docs.ts; DO NOT EDIT. -->';
const directory = 'docs/shared-systems';
const order = (a: string, b: string) => a < b ? -1 : a > b ? 1 : 0;
const check = (condition: unknown, message: string): void => { if (!condition) throw new Error(message); };
const prose = (value: string) => value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replace(/[\\`*_\[\]{}()#+.!|]/g, '\\$&').replace(/\r?\n/g, '<br>');
const ticks = (value: string, minimum: number) => '`'.repeat(Math.max(minimum, ...(value.match(/`+/g) ?? []).map(run => run.length + 1)));
const code = (value: string) => { const edge = ticks(value, 1); return edge + (value.startsWith('`') || value.endsWith('`') ? ` ${value} ` : value) + edge; };
const block = (value: string, language: string) => { const edge = ticks(value, 3); return `${edge}${language}\n${value}\n${edge}`; };
const cell = (value: string) => value.replace(/(\\*)\|/g, (match, slashes: string) => slashes.length % 2 ? match : `${slashes}\\|`);
const rows = (header: string[], values: string[][]) => [header, header.map(() => '---'), ...values].map(row => `| ${row.map(cell).join(' | ')} |`).join('\n');
const page = (title: string, content: string[]) => `${GENERATED_SHARED_SYSTEM_DOCS}\n\n# ${title}\n\n${content.join('\n\n')}\n`;
const footer = '[목록으로](../README.md) · [공통 규칙](../contracts.md) · [월드 제작 가이드](../../../.claude/skills/add-world/SKILL.md)';
const exampleLocation = `아래 코드를 ${code('shared/my-shared-map.ts')}에 저장합니다. 서버 등록과 불러오기 순서는 [월드 제작 가이드](../../../.claude/skills/add-world/SKILL.md)를 따릅니다.`;
export function documentedContentText(metadata: ContentMetadata, key: string, field: string, source: string) {
  const defined = metadata.entries[key]?.fields[field];
  return defined?.source === source ? defined.translations?.ko ?? source : source;
}

function exampleJson(value: unknown, indent = 2): string {
  if (Array.isArray(value)) {
    if (value.every(part => part === null || typeof part !== 'object')) return `[${value.map(part => JSON.stringify(part)).join(', ')}]`;
    return `[\n${value.map(part => ' '.repeat(indent + 2) + exampleJson(part, indent + 2)).join(',\n')}\n${' '.repeat(indent)}]`;
  }
  if (value !== null && typeof value === 'object') {
    const entries = Object.entries(value);
    if (!entries.length) return '{}';
    return `{\n${entries.map(([key, part]) => `${' '.repeat(indent + 2)}${JSON.stringify(key)}: ${exampleJson(part, indent + 2)}`).join(',\n')}\n${' '.repeat(indent)}}`;
  }
  return JSON.stringify(value);
}

export function itemPlacementExample(item: SystemItemDefinition, controlled = false): string {
  const placement = {
    id: 'my-item', itemId: item.id, position: [0, 0, -2],
    ...(controlled ? { itemMode: 'system', capabilities: ['interact'] } : {}),
  };
  return `import { createSystemMap } from './system-map.ts';\n\nexport const myMap = createSystemMap('my-map')\n  .item(${exampleJson(placement)})\n  .build();`;
}

export function systemPlacementExample(manifest: SystemManifest): string {
  const map = catalogExampleMap(manifest);
  const placements = map.objects.map(object => {
    if (!object.capabilities.includes('text')) return `  .object(${exampleJson(object)})\n`;
    const { id, ...properties } = object;
    return `  .item(${exampleJson({ id, itemId: 'note', itemMode: 'system', ...properties })})\n`;
  }).join('');
  return `import { createSystemMap } from './system-map.ts';\n\nexport const myMap = createSystemMap(${JSON.stringify(map.id)})\n${placements}  .system(${exampleJson(map.systems[0])})\n  .build();`;
}

