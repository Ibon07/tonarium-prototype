import { readFantasySavedProfiles } from './fantasy-test-saved-profiles.ts';
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import http from 'node:http';
import net from 'node:net';
import { spawn } from 'node:child_process';
import { WebSocket } from 'ws';
import { BROWSER_AI_MODEL, type BrowserAiJob } from '../shared/ai-support.ts';
import { applyFantasyAction, newFantasyProfile } from '../shared/fantasy-engine.ts';
import { NPC_SERVER } from './npc-catalog.ts';

test('real sockets keep browser inference private, commit once, fall back after opt-out and reject stale world context',async t=>{
  const prefix=path.join(os.tmpdir(),'tonarium-browser-ai-wire-'),directory=fs.mkdtempSync(prefix);
  const profiles=Object.fromEntries(['alice','bob'].map(id=>[id,applyFantasyAction(newFantasyProfile(),{type:'create',name:id,source:'human',gender:'female'},()=>.5).profile]));
  fs.writeFileSync(path.join(directory,'fantasy.json'),JSON.stringify(profiles));
  const sessions=path.join(directory,'sessions.json');
  fs.writeFileSync(sessions,JSON.stringify({name:'AI test',sessions:[{id:'world',name:'AI test',world:'fantasy'}]}));
  let localCalls=0;
  const serverAnswers:string[][]=[];
  const local=http.createServer(async(req,res)=>{
    let data='';for await(const chunk of req)data+=String(chunk);
    const request=JSON.parse(data) as {messages:{content:string}[]};
    localCalls++;serverAnswers.push(request.messages.map(message=>message.content));
    res.writeHead(200,{'Content-Type':'application/json'});res.end(JSON.stringify({model:'unchanged-central-model',choices:[{message:{content:'Rest here a moment; the road can wait until you feel ready.'}}]}));
  });
  await new Promise<void>(resolve=>local.listen(0,'127.0.0.1',resolve));
  const localPort=(local.address() as net.AddressInfo).port;
  const listener=net.createServer();await new Promise<void>(resolve=>listener.listen(0,'127.0.0.1',resolve));
  const port=(listener.address() as net.AddressInfo).port;await new Promise<void>(resolve=>listener.close(()=>resolve()));
  const child=spawn(process.execPath,['--import','tsx','server/index.ts','--dev'],{env:{...process.env, NODE_ENV: 'test', FANTASY_ACCOUNT_TEST_BYPASS: '1',SERVER_PORT:String(port),DATA_DIR:directory,SESSIONS_FILE:sessions,NPC_LLM_URL:`http://127.0.0.1:${localPort}/v1`,NPC_LLM_MODEL:'unchanged-central-model',LIVEKIT_URL:'',LIVEKIT_API_KEY:'',LIVEKIT_API_SECRET:''},stdio:['ignore','pipe','pipe']});
  let logs='';child.stdout.on('data',data=>logs+=String(data));child.stderr.on('data',data=>logs+=String(data));
  const sockets:WebSocket[]=[];
  t.after(async()=>{
    for(const socket of sockets)socket.terminate();child.kill();
    if(child.exitCode===null&&!child.signalCode)await new Promise<void>(resolve=>{const timer=setTimeout(()=>{child.kill('SIGKILL');resolve();},3000);child.once('exit',()=>{clearTimeout(timer);resolve();});});
    await new Promise<void>(resolve=>local.close(()=>resolve()));
    if(!path.resolve(directory).startsWith(path.resolve(prefix)))throw Error('Invalid test directory');
    fs.rmSync(directory,{recursive:true,force:true});
  });
  async function until<T>(read:()=>T|undefined,timeout=8000):Promise<T>{const end=Date.now()+timeout;while(Date.now()<end){const value=read();if(value!==undefined)return value;if(child.exitCode!==null)throw Error(logs);await new Promise(resolve=>setTimeout(resolve,10));}throw Error('Timed out: '+logs);}
  await until(()=>logs.includes('server on')?true:undefined,20000);
  type Message={t:string;requestId?:string;job?:BrowserAiJob;leaseId?:string;source?:string;model?:string;actions?:unknown[];reply?:{text:string;suggestions:unknown[]};text?:string;error?:string};
  const peer=async(id:string)=>{
    const socket=new WebSocket(`ws://127.0.0.1:${port}/ws`);sockets.push(socket);
    const messages:Message[]=[];socket.on('message',raw=>messages.push(JSON.parse(String(raw))));
    await new Promise<void>((resolve,reject)=>{socket.once('open',resolve);socket.once('error',reject);});
    const send=(message:unknown)=>socket.send(JSON.stringify(message));send({t:'hello',id,name:id});send({t:'join',sid:'world'});
    await until(()=>messages.find(message=>message.t==='fantasyProfile'));
    return{socket,messages,send};
  };
  const alice=await peer('alice'),bob=await peer('bob'),otherAlice=await peer('alice');
  const question={t:'npcChat',npcId:'rin',locale:'en',requestId:'browser-npc',text:'Please share a comforting thought about feeling lonely.'};
  alice.send({t:'aiSupport',ready:true,epoch:'alice-epoch',model:BROWSER_AI_MODEL});alice.send(question);
  const job=(await until(()=>alice.messages.find(message=>message.t==='aiSupportJob'))).job!;
  assert.equal(job.kind,'npc');assert.equal(job.epoch,'alice-epoch');
  const prompt=job.messages.map(message=>message.content).join('\n');
  for(const secret of Object.values(NPC_SERVER).flatMap(npc=>npc.privateSecrets))assert.equal(prompt.includes(secret),false);
  assert.equal(bob.messages.some(message=>message.t==='aiSupportJob'),false);
  assert.equal(otherAlice.messages.some(message=>message.t==='aiSupportJob'),false);
  bob.send({t:'aiSupportResult',leaseId:job.leaseId,epoch:job.epoch,text:'A forged answer from Bob.'});
  alice.send({t:'aiSupportResult',leaseId:job.leaseId,epoch:job.epoch,text:'You can take a quiet breath and rest here.'});
  const browser=await until(()=>alice.messages.find(message=>message.t==='npcReply'&&message.requestId===question.requestId));
  assert.equal(browser.source,'browser');assert.equal(browser.model,BROWSER_AI_MODEL);assert.equal(browser.actions,undefined);assert.equal(localCalls,0);
  alice.send({t:'aiSupportResult',leaseId:job.leaseId,epoch:job.epoch,text:'A duplicated response.'});
  assert.equal(alice.messages.filter(message=>message.t==='npcReply'&&message.requestId===question.requestId).length,1);

  alice.send({t:'fantasyGmChat',locale:'en',requestId:'browser-gm',text:'I feel lonely. Can you share a short comforting thought?'});
  const gm=(await until(()=>alice.messages.find(message=>message.job?.requestId==='browser-gm'))).job!;
  alice.send({t:'aiSupportResult',leaseId:gm.leaseId,epoch:gm.epoch,text:'There is room for a quieter moment in your journey.'});
  const gmReply=await until(()=>alice.messages.find(message=>message.t==='fantasyGmReply'&&message.requestId==='browser-gm'));
  assert.equal(gmReply.source,'browser');assert.deepEqual(gmReply.reply?.suggestions,[]);assert.equal(localCalls,0);

  await new Promise(resolve=>setTimeout(resolve,1550));
  alice.send({...question,requestId:'browser-fallback',text:'I am feeling nervous. Please offer a little encouragement.'});
  const fallback=(await until(()=>alice.messages.find(message=>message.job?.requestId==='browser-fallback'))).job!;
  alice.send({t:'aiSupport',ready:false,epoch:'alice-epoch',model:BROWSER_AI_MODEL});
  const central=await until(()=>alice.messages.find(message=>message.t==='npcReply'&&message.requestId==='browser-fallback'));
  assert.equal(central.source,'local');assert.equal(central.model,'unchanged-central-model');assert.equal(localCalls,1);
  assert.ok(alice.messages.some(message=>message.t==='aiSupportCancel'&&message.leaseId===fallback.leaseId));
  alice.send({t:'aiSupportResult',leaseId:fallback.leaseId,epoch:fallback.epoch,text:'Too late to replace the server.'});
  await new Promise(resolve=>setTimeout(resolve,1550));
  alice.send({...question,requestId:'server-default',text:'Could you tell me a quiet story about patience?'});
  assert.equal((await until(()=>alice.messages.find(message=>message.t==='npcReply'&&message.requestId==='server-default'))).source,'local');
  assert.equal(localCalls,2);assert.equal(serverAnswers.at(-1)!.some(text=>text.includes('Too late to replace')),false);
  const saved=readFantasySavedProfiles(path.join(directory,'fantasy.json'));
  assert.equal(saved.alice.character!.gold,profiles.alice.character!.gold);assert.deepEqual(saved.alice.character!.inventory,profiles.alice.character!.inventory);

  alice.send({t:'aiSupport',ready:true,epoch:'new-alice-epoch',model:BROWSER_AI_MODEL});
  alice.send({t:'fantasyGmChat',locale:'en',requestId:'stale-world',text:'Could you offer a quiet thought about being patient?'});
  const stale=(await until(()=>alice.messages.find(message=>message.job?.requestId==='stale-world'))).job!;
  alice.send({t:'leave'});
  alice.send({t:'aiSupportResult',leaseId:stale.leaseId,epoch:stale.epoch,text:'This must never enter the history after leaving the world.'});
  const staleReply=await until(()=>alice.messages.find(message=>message.t==='fantasyGmReply'&&message.requestId==='stale-world'));
  assert.equal(staleReply.error,'invalid');assert.equal(localCalls,2);
  alice.send({t:'join',sid:'world'});
  await new Promise(resolve=>setTimeout(resolve,1550));
  alice.send({t:'fantasyGmChat',locale:'en',requestId:'fresh-world',text:'Could you offer another quiet thought about being patient?'});
  const fresh=(await until(()=>alice.messages.find(message=>message.job?.requestId==='fresh-world'))).job!;
  assert.equal(fresh.messages.some(message=>message.content.includes('This must never enter the history')),false);
  alice.send({t:'aiSupportResult',leaseId:fresh.leaseId,epoch:fresh.epoch,text:'Patience makes room for a calmer moment.'});
  assert.equal((await until(()=>alice.messages.find(message=>message.t==='fantasyGmReply'&&message.requestId==='fresh-world'))).source,'browser');

  alice.send({t:'leave'});
  alice.send({t:'aiSupport',ready:true,epoch:'outside-world-epoch',model:BROWSER_AI_MODEL});
  alice.send({...question,requestId:'outside-world',text:'Please share a quiet word about finding courage.'});
  const outside=await until(()=>alice.messages.find(message=>message.t==='npcReply'&&message.requestId==='outside-world'));
  assert.equal(outside.source,'local');assert.equal(outside.model,'unchanged-central-model');assert.equal(localCalls,3);
  assert.equal(alice.messages.some(message=>message.job?.requestId==='outside-world'),false);
  alice.send({t:'join',sid:'world'});
  alice.send({...question,requestId:'not-ready-after-rejoin',text:'Please share one more quiet word about finding courage.'});
  assert.equal((await until(()=>alice.messages.find(message=>message.t==='npcReply'&&message.requestId==='not-ready-after-rejoin'))).source,'local');
  assert.equal(localCalls,4);assert.equal(alice.messages.some(message=>message.job?.requestId==='not-ready-after-rejoin'),false);
});
